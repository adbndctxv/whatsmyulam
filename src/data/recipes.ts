// ing("garlic", 6, "clove", { note: "crushed" })
function ing(
  ingredientId: string,
  quantity: number,
  unit: Unit,
  extra: Partial<RecipeIngredient> = {},
): RecipeIngredient {
  return { ingredientId, quantity, unit, ...extra };
}

// taste("salt")  ->  "to taste", with no invented quantity
function taste(ingredientId: string, extra: Partial<RecipeIngredient> = {}): RecipeIngredient {
  return { ingredientId, quantity: null, unit: null, toTaste: true, ...extra };
}

